            r = ride() r.tick() r.tick()
            local before = r.state
            r.sample.identity = table.clone(r.sample.identity) r.sample.identity[field] = {}
            r.sample.raw_phase = .7
            out = r.tick()
            check(out.rebased and not out.advanced and angle_near(out.state.phase, .7) and
                not rawequal(out.state.identity[field], before.identity[field]), "a new body or owner reseeds")
        end
        for mode = 1, 3 do
