    ------------------------------------------------------------ crank
    local function ride(raw)
        local r = {state = P.crank_state(), sample = {identity = identity(1), raw_phase = raw or -2.6332650184631348,
            time = 0, seconds = 1 / 60, serial = 1, enabled = true, pedaling = false, reserved = false}}
        function r.tick()
            local s = table.clone(r.sample) s.serial = tostring(s.serial)
            local out = P.step_crank(r.state, s)
            r.state = out.state
            r.sample.serial += 1
            r.sample.time += r.sample.seconds
            return out
        end
        function r.current()
            local s = table.clone(r.sample) s.serial = tostring(s.serial) return s
        end
        return r
    end

