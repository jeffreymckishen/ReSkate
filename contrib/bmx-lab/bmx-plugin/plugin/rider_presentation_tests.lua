            check(angle_near(a, P.source_horizontal_angle()), "uniform scale keeps the level angle")
        end
        check(P.remainder(5 * math.pi, 2 * math.pi) == math.pi and P.remainder(-5 * math.pi, 2 * math.pi) == -math.pi,
