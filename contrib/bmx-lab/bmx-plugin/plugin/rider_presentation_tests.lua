    ------------------------------------------------------------ presenter
    case("presenter steps each native sample once and resets on owner changes", function()
        local p = P.new()
        local g = 12 * P.radians_per_degree
        local n = {0, math.cos(g), -math.sin(g)}
        local function sample(serial, extra)
            local s = {identity = identity(1), serial = tostring(serial), time = serial * H, seconds = H,
                raw_crank_phase = 1, enabled = true, airborne = false, supported = true,
                evidence = {valid = true, first_contact = false, post_available = true, contact_serial = "1",
                    post_closing_speed = 0, scoring_closing_speed = 0},
                wheels = {supported = {true, true}, normal_available = {true, true}, normal = {n, n}},
                forward = {0, math.sin(g), math.cos(g)}, orientation = axis({1, 0, 0}, -g)}
            for key, value in pairs(extra or {}) do s[key] = value end
            return s
        end
        local out = p:step(sample(1, {evidence = touch(1, 3)}))
        check(out.valid and out.advanced and near(out.landing.compression, .5, 1e-12), "a first touch compresses")
        check(out.articulation.crank_phase == out.crank.state.phase and out.rider.hip_offset[2] < 0, "outputs mapped")
        local again = p:step(sample(1, {evidence = touch(1, 3)}))
        check(again.valid and not again.advanced and again.hold == "duplicate" and
            again.landing.compression == out.landing.compression, "a duplicate cannot pulse or decay twice")
        local paused = p:step(sample(2, {seconds = 0}))
        check(not paused.advanced and paused.hold == "paused", "a pause spends nothing")
        for serial = 2, 40 do out = p:step(sample(serial)) end
        check(out.valid and out.posture_available and out.posture.state.uphill > .3, "an incline cue builds")
        check(out.gaze_counterpitch > 0 and out.landing.compression == 0, "gaze up, landing recovered")
        local leveled = out.articulation.crank_phase
        check(math.abs(P.remainder(leveled - P.source_horizontal_angle(), math.pi)) < 1e-9, "the coasting crank levels")
        local bad = p:step(sample(41, {forward = {0, 2, 0}}))
        check(bad.valid and not bad.posture_available and bad.articulation ~= nil, "a posture refusal clears only posture")
        out = p:step(sample(42, {evidence = touch(42, 6)}))
        check(out.landing.compression == 1, "a hard landing")
        out = p:step(sample(43, {identity = identity(2)}))
        check(out.reset and out.landing.compression == 0 and out.crank.rebased, "a new body clears the old pose")
        out = p:step(sample(44, {identity = identity(2), evidence = touch(44, 6)}))
        out = p:step(sample(10, {identity = identity(2)}))
        check(out.reset and out.landing.compression == 0, "a rewound serial clears presentation")
        out = p:step(sample(11, {identity = identity(2), seconds = .2}))
        check(not out.valid and out.reset, "a refused native step resets")
        out = p:step(sample(12, {identity = identity(2), orientation = {0, 0, 0, 2}}))
        check(not out.valid and out.issue == "invalid orientation", "unmappable outputs are not valid")
    end)

    -- A bad clock or crank phase must refuse the whole composite before the
    -- duplicate and pause shortcuts can hold an older valid pose, and a refused
    -- crank step must not let the other cues advance or be cached.
    local function clock_sample(serial, extra)
        local s = {identity = identity(1), serial = tostring(serial), time = serial * H, seconds = H,
            raw_crank_phase = 1, enabled = true, airborne = false, supported = true,
            evidence = {valid = true, first_contact = false, post_available = true, contact_serial = "1",
                post_closing_speed = 0, scoring_closing_speed = 0},
            wheels = {supported = {true, true}, normal_available = {true, true}, normal = {{0, 1, 0}, {0, 1, 0}}},
            forward = {0, 0, 1}, orientation = {0, 0, 0, 1}}
        for key, value in pairs(extra or {}) do s[key] = value end
        return s
    end
    local function seeded()
        local p = P.new()
        local s = clock_sample(1)
        s.evidence.first_contact, s.evidence.post_closing_speed, s.evidence.scoring_closing_speed = true, 3, 3
        local out = p:step(s)
        check(out.valid and out.advanced and out.landing.compression == .5, "presenter seeded with a landing compression")
        return p, out
    end
    local function composite_refused(out)
        return out.valid == false and out.advanced == false and out.reset == true
            and out.articulation == nil and out.rider == nil
    end

    case("presenter duplicates, pauses, repeated raw phases and rebases stay valid", function()
        local p, first = seeded()
        local same = p:step(clock_sample(1))
        check(same.valid and not same.advanced and same.hold == "duplicate", "a real duplicate holds")
        check(same.landing.compression == first.landing.compression, "a duplicate spends no compression")
        local pause = p:step(clock_sample(2, {seconds = 0}))
        check(pause.valid and not pause.advanced and pause.hold == "paused", "a pause holds without consuming a new serial")
        local resumed = p:step(clock_sample(2))
        check(resumed.valid and resumed.advanced and resumed.crank.advanced, "the fresh successor resumes after a pause")
        check(near(resumed.landing.compression, .5 - 4 * H, 1e-12), "only the successor spends recovery")

        p, first = seeded()
        local raw_change = p:step(clock_sample(1, {raw_crank_phase = 2}))
        check(raw_change.valid and raw_change.hold == "duplicate" and
            raw_change.articulation.crank_phase == first.articulation.crank_phase,
            "a finite raw change at the same serial and time is ignored, as step_crank does")

        p, first = seeded()
        local paused = p:step(clock_sample(1, {seconds = 0, time = 10}))
        check(paused.valid and paused.hold == "paused" and p.crank.time == H,
            "a paused time need not equal the last consumed clock")
        check(paused.landing.compression == first.landing.compression, "a pause cannot spend the landing cue")

        p = seeded()
        local posture = p:step(clock_sample(2, {forward = {0, 2, 0}}))
        check(posture.valid and not posture.posture_available and posture.articulation ~= nil,
            "an invalid plane clears only posture")

        p = seeded()
        local owner = p:step(clock_sample(10, {identity = identity(2)}))
        check(owner.valid and owner.reset and owner.crank.rebased, "an owner change rebases without refusing a valid clock")
        owner = p:step(clock_sample(40))
        check(owner.valid and owner.reset and owner.crank.rebased, "the old owner returning is a fresh rebase")
    end)

    case("presenter refuses invalid clocks and phases before a duplicate or a pause can hold", function()
        local bad_values = {
            {name = "nan time", field = "time", value = 0 / 0},
            {name = "infinite time", field = "time", value = math.huge},
            {name = "negative time", field = "time", value = -H},
            {name = "nan phase", field = "raw_crank_phase", value = 0 / 0},
            {name = "infinite phase", field = "raw_crank_phase", value = math.huge},
            {name = "phase outside 1e6", field = "raw_crank_phase", value = 1000001},
        }
        for _, bad in ipairs(bad_values) do
            for _, mode in ipairs({"fresh", "duplicate", "paused"}) do
                local label = mode .. " " .. bad.name
                local p = seeded()
                local s = clock_sample(mode == "duplicate" and 1 or 2)
                if mode == "paused" then s.seconds = 0 end
                s[bad.field] = bad.value
                local out = p:step(s)
                check(composite_refused(out), label .. ": refuses the entire composite, never holds an older valid pose")
                check(p.last == nil and p.serial == nil and p.compression == 0 and p.air_extension == 0,
                    label .. ": the refusal clears aggregate state and consumes no serial")
                local resumed = p:step(clock_sample(3))
                check(resumed.valid and resumed.crank.rebased and resumed.landing.compression == 0,
                    label .. ": a fresh valid read resumes without spending the rejected input")
            end
        end
    end)

    case("presenter refuses a duplicate serial at a changed active time", function()
        local p = seeded()
        local out = p:step(clock_sample(1, {time = 2 * H}))
        check(composite_refused(out) and out.issue == "duplicate_changed",
            "the same serial at another consumed time is contradictory")
        check(p.last == nil and p.serial == nil and p.crank.observed == false,
            "the contradiction cannot remain a valid held output")
    end)

    return {cases = cases, assertions = assertions}
end

