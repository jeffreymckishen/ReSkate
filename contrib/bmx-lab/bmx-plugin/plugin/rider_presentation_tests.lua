local function bit(x) return x == 1 end
local bodies, leases = {{}, {}}, {{}, {}}
-- C++ owner/world/body-token identities k = 1, 2 become distinct Lua handles;
-- 0 (no body token) and -1 (one null owner pointer) become incomplete keys.
local function identity(id)
    if id == 0 then return {body_handle = nil, lease_handle = leases[1]} end
    if id < 0 then return {body_handle = bodies[1], lease_handle = nil} end
    return {body_handle = bodies[id], lease_handle = leases[id]}
end
local function grade_sample(grade, seconds, serial, yaw)
    yaw = yaw or 0
    local n = {-math.sin(grade) * math.sin(yaw), math.cos(grade), -math.sin(grade) * math.cos(yaw)}
    return {seconds = seconds, serial = tostring(serial), supported = {true, true}, normal_available = {true, true},
        normal = {n, table.clone(n)}, forward = {math.cos(grade) * math.sin(yaw), math.sin(grade), math.cos(grade) * math.cos(yaw)}}
end
local function axis(n, angle)
    local s = math.sin(angle * .5)
    return {n[1] * s, n[2] * s, n[3] * s, math.cos(angle * .5)}
end
local function multiply(a, b)
    return {a[4] * b[1] + a[1] * b[4] + a[2] * b[3] - a[3] * b[2], a[4] * b[2] - a[1] * b[3] + a[2] * b[4] + a[3] * b[1],
        a[4] * b[3] + a[1] * b[2] - a[2] * b[1] + a[3] * b[4], a[4] * b[4] - a[1] * b[1] - a[2] * b[2] - a[3] * b[3]}
end

function Tests.run(progress)
    local assertions, cases = 0, 0
    local function check(condition, message)
        assertions = assertions + 1
        assert(condition, message)
    end
    local function near(a, b, tolerance) return math.abs(a - b) <= (tolerance or 1e-12) end
    local function angle_near(a, b, tolerance) return math.abs(P.wrap(a - b)) <= (tolerance or 1e-11) end
    local function case(name, body)
        cases = cases + 1
        local ok, issue = pcall(body)
        if not ok then error(name .. ": " .. tostring(issue), 0) end
        if type(progress) == "function" then progress(cases, assertions) end
    end

    case("module is pure and frozen", function()
        check(table.isfrozen(P), "module table is frozen")
        check(near(P.maximum_counterpitch, 25 * math.pi / 180, 1e-15) and near(P.counterpitch_rate, 90 * math.pi / 180, 1e-15),
