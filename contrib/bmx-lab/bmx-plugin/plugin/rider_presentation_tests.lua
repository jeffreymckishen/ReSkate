                "a gap, backward clock or time mismatch never catches up")
        end
        local bad = {function(s) s.raw_phase = NAN end, function(s) s.seconds = INF end, function(s) s.time = NAN end,
            function(s) s.seconds = -.01 end, function(s) s.seconds = .11 end, function(s) s.raw_phase = 1e6 + 1 end,
