            out = P.step_crank(before, s)
            check(not out.valid and out.state.phase == before.phase and out.state.serial == before.serial,
                "an invalid scalar or incomplete identity cannot mutate phase or history")
        end
        local a, b = ride(), ride()
        a.tick() b.tick()
        b.sample.seconds = 1 / 30 b.sample.time = b.state.time + b.sample.seconds
        for _ = 1, 12 do a.tick() end
        for _ = 1, 6 do b.tick() end
        check(angle_near(a.state.phase, b.state.phase), "leveling speed follows native time, not callback count")
        local top = {identity = identity(1), raw_phase = 0, time = 1, seconds = H, serial = "18446744073709551614",
            enabled = true}
